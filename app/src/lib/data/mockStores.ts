type ApiProductLike = {
  id?: number | string;
  title?: string;
  category?: string;
  price_usdc?: number | string;
  moq?: number | string;
  lead_time_days?: number | string;
  rating?: number | string;
  seller_tier?: string;
  usdc_mint?: string;
  is_verified?: boolean;
};

export function mapApiProductToDashboardProduct(
  product: ApiProductLike,
  vendor: string,
  sellerWallet: string,
  vendorType: StoreVendorType
): DashboardProduct {
  const fallbackTier = vendorTypeToSellerTier(vendorType);
  const sellerTierRaw = String(product.seller_tier ?? "").toLowerCase();
  const sellerTier: DashboardProduct["sellerTier"] =
    sellerTierRaw === "manufacturer" || sellerTierRaw === "wholesaler" || sellerTierRaw === "distributor"
      ? sellerTierRaw
      : fallbackTier;

  const numericPrice = Number(product.price_usdc ?? 0);
  const numericMoq = Number(product.moq ?? 1);
  const numericLeadTime = Number(product.lead_time_days ?? 7);
  const numericRating = Number(product.rating ?? 4.5);

  return {
    productId: String(product.id ?? `${sellerWallet.slice(0, 8)}-${vendor}-${Date.now()}`),
    title: String(product.title ?? "Untitled Product"),
    category: String(product.category ?? "General"),
    vendor,
    sellerWallet,
    sellerTier,
    rating: Number.isFinite(numericRating) ? numericRating : 4.5,
    priceUsdc: Number.isFinite(numericPrice) ? numericPrice : 0,
    moq: Number.isFinite(numericMoq) ? numericMoq : 1,
    leadTimeDays: Number.isFinite(numericLeadTime) ? numericLeadTime : 7,
    usdcMint: String(product.usdc_mint ?? "4zMMC9srt5Ri5X14GAgXhaHii3GnPAEERYPJgZJDncDU"),
    isVerified: product.is_verified ?? true,
  };
}
